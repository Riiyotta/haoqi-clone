#!/usr/bin/env python3
"""Build schema/pagespec.schema.json (Draft-07) from the section contracts, asset roles, motion patterns,
templates and the token policy, so the machine contract can never silently diverge from them.

    python3 schema/build_schema.py           # write
    python3 schema/build_schema.py --check   # exit 1 if the committed schema differs (used by verify_all.py)
"""
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "schema" / "pagespec.schema.json"


def load(rel):
    return json.loads((REPO / rel).read_text())


def strip(s):
    """Drop design-repo annotations that are not Draft-07 keywords (kept in the contracts, enforced semantically)."""
    if isinstance(s, dict):
        return {k: strip(v) for k, v in s.items() if k not in ("maxWords", "observedWords")}
    if isinstance(s, list):
        return [strip(v) for v in s]
    return s


def build():
    sections = {p.stem: json.loads(p.read_text()) for p in sorted((REPO / "sections").glob("*.json"))}
    roles = sorted(load("assets/asset-roles.json")["roles"])
    patterns = load("tokens/00-foundation/motion-patterns.json")["patterns"]
    templates = sorted(load("templates/templates.json")["templates"])
    policy = load("tokens/llm/token-policy.json")
    # values stay plain strings here so the semantic layer can name the exact TOKEN_* violation
    style_props = {f: {"type": "string", "minLength": 1, "maxLength": 60} for f in policy["styleFields"]}
    defs = {
        "assetRef": {"type": "object", "additionalProperties": False, "required": ["role", "ref"],
                     "properties": {"role": {"type": "string", "enum": roles}, "ref": {"type": "string", "minLength": 1, "maxLength": 300},
                                    "alt": {"type": "string", "maxLength": 200}}},
        "style": {"type": "object", "additionalProperties": False, "properties": style_props},
    }
    node_refs = []
    for sid, c in sections.items():
        motion_alts = [{"type": "object", "additionalProperties": False, "required": ["pattern", "reducedMotionFallback"],
                        "properties": {"pattern": {"const": m}, "reducedMotionFallback": {"const": patterns[m]["reducedMotionFallback"]},
                                       "trigger": {"type": "string", "enum": ["on-enter", "on-scroll", "on-hover", "on-load", "on-route", "continuous"]}}}
                       for m in c["motion"]["allowedPatterns"]]
        slots = c["assets"]["slots"]
        slot_schema = {"type": "string", "enum": slots} if not any("[i]" in s for s in slots) else \
            {"type": "string", "pattern": "^(" + "|".join(s.replace("[", "\\[").replace("]", "\\]").replace("\\[i\\]", "\\[[0-9]+\\]").replace(".", "\\.") for s in slots) + ")$"}
        props = {
            "section": {"const": sid},
            "content": strip(c["contentSchema"]),
            "motion": {"oneOf": motion_alts} if len(motion_alts) > 1 else motion_alts[0],
            "retrievalEligible": {"type": "boolean"},
        }
        if c["variants"]:
            props["variant"] = {"type": "string", "enum": c["variants"]}
        if slots:
            props["assets"] = {"type": "array", "items": {"allOf": [{"$ref": "#/definitions/assetRef"},
                                                                       {"type": "object", "required": ["slot"], "properties": {"slot": slot_schema}}]}}
        if c["styleOverrides"]:
            props["style"] = {"type": "object", "additionalProperties": False, "properties": {k: style_props[k] for k in c["styleOverrides"]}}
        required = ["section", "content", "motion"] + (["variant"] if c["variants"] else [])
        name = "node_" + sid.replace(".", "_").replace("-", "_")
        # assetRef + slot: closed by listing every allowed key on the node-level asset item
        if slots:
            props["assets"]["items"] = {"type": "object", "additionalProperties": False, "required": ["slot", "role", "ref"],
                                        "properties": {"slot": slot_schema, "role": {"type": "string", "enum": roles},
                                                       "ref": {"type": "string", "minLength": 1, "maxLength": 300}, "alt": {"type": "string", "maxLength": 200}}}
        defs[name] = {"type": "object", "additionalProperties": False, "required": required, "properties": props}
        node_refs.append({"$ref": f"#/definitions/{name}"})
    schema = {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": "https://design-repo.invalid/haoqi-portfolio/pagespec.schema.json",
        "title": "PageSpec (GENERATED by schema/build_schema.py from sections/, assets/, tokens/, templates/ - do not hand-edit)",
        "type": "object", "additionalProperties": False,
        "required": ["pageSpecVersion", "mode", "template", "route", "theme", "brand", "meta", "nodes"],
        "properties": {
            "pageSpecVersion": {"const": "1.0.0"},
            "mode": {"type": "string", "enum": ["reference", "generated"],
                     "description": "reference = faithful description of the source; generated = new page that must contain nothing identifying or reproducing the source (semantic rules GENERATED_MODE_*)."},
            "template": {"type": "string", "enum": templates},
            "route": {"type": "string", "pattern": "^/[A-Za-z0-9_\\-/]*$"},
            "theme": {"type": "string", "enum": ["light", "dark", "system"]},
            "brand": {"type": "object", "additionalProperties": False, "required": ["name", "markRole"],
                      "properties": {"name": {"type": "string", "minLength": 1, "maxLength": 40}, "markRole": {"type": "string", "enum": roles}}},
            "meta": {"type": "object", "additionalProperties": False, "required": ["title"],
                     "properties": {"title": {"type": "string", "minLength": 1, "maxLength": 80}, "description": {"type": "string", "maxLength": 200}}},
            "nodes": {"type": "array", "minItems": 1, "items": {"oneOf": node_refs}},
        },
        "definitions": defs,
    }
    return schema


def main():
    s = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != s:
            print("FAIL: schema/pagespec.schema.json is out of sync with the contracts (run schema/build_schema.py)")
            return 1
        print("ok: pagespec.schema.json in sync with contracts")
        return 0
    OUT.write_text(s)
    print("wrote schema/pagespec.schema.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
